"""
Fill the database with realistic demo sales so the reports dashboard has something to show.

    python manage.py seed_demo_sales            # add demo matches, fans, bookings, payments
    python manage.py seed_demo_sales --clear    # remove everything this command created

Demo records are marked so --clear can find them: fans are named demo_fan_<n> and demo
matches have a description starting with DEMO_MARKER. No emails are sent.
"""
import random
from datetime import datetime, time, timedelta

from django.core.management.base import BaseCommand, CommandError
from django.db import transaction
from django.utils import timezone

from bookings.models import Booking
from events.models import Event
from payments.models import Payment
from tickets.models import Ticket
from users.models import Fan, User
from venues.models import Venue

DEMO_MARKER = 'DEMO DATA'
DEMO_FAN_PREFIX = 'demo_fan_'

# (title, days from today, kick-off) - negative = already played
DEMO_MATCHES = [
    ('Tusker FC vs Kakamega Homeboyz', -24, time(15)),
    ('Shabana FC vs Kenya Police', -10, time(16)),
    ('Harambee Stars vs Uganda Cranes', 6, time(18)),
    ('Bandari FC vs Ulinzi Stars', 20, time(15)),
]


class Command(BaseCommand):
    help = 'Create (or --clear) demo matches, fans, bookings and payments for the reports dashboard.'

    def add_arguments(self, parser):
        parser.add_argument('--venue', default='Kasarani Stadium', help='Venue name to use.')
        parser.add_argument('--fans', type=int, default=40)
        parser.add_argument('--seed', type=int, default=7, help='Random seed (same seed = same data).')
        parser.add_argument('--organizer', help='Username of the organizer who owns the demo matches '
                                                    '(default: none, so only admins see them in reports).')
        parser.add_argument('--clear', action='store_true', help='Delete all demo data and exit.')

    def handle(self, *args, **opts):
        if opts['clear']:
            return self.clear()

        venue = Venue.objects.filter(name=opts['venue']).first()
        if not venue:
            raise CommandError(f'Venue "{opts["venue"]}" not found. Run seed_venue first.')
        organizer = None
        if opts['organizer']:
            organizer = User.objects.filter(username=opts['organizer']).first()
            if not organizer:
                raise CommandError(f'User "{opts["organizer"]}" not found.')
        if Event.objects.filter(description__startswith=DEMO_MARKER).exists():
            raise CommandError('Demo data already exists. Run with --clear first to recreate it.')

        rng = random.Random(opts['seed'])
        with transaction.atomic():
            fans = self.make_fans(opts['fans'])
            seats = list(venue.seats.select_related('category'))
            rows = max(s.row_number for s in seats)
            cols = max(s.seat_number for s in seats)
            totals = {'bookings': 0, 'revenue': 0, 'refunds': 0}

            for title, offset, kickoff in DEMO_MATCHES:
                event_date = timezone.localdate() + timedelta(days=offset)
                event = Event.objects.create(
                    title=title, venue=venue, organizer=organizer, event_date=event_date, event_time=kickoff,
                    status='completed' if offset < 0 else 'upcoming',
                    description=f'{DEMO_MARKER} - generated by seed_demo_sales',
                )
                # Bigger games sell more.
                demand = 0.55 if 'Harambee' in title else rng.uniform(0.25, 0.45)
                self.sell(event, seats, rows, cols, fans, demand, rng, totals)

        self.stdout.write(self.style.SUCCESS(
            f'Created {len(DEMO_MATCHES)} demo matches, {opts["fans"]} demo fans, '
            f'{totals["bookings"]} bookings (KES {totals["revenue"]:,.0f} revenue, '
            f'{totals["refunds"]} refund due).'))

    def make_fans(self, count):
        fans = []
        for i in range(1, count + 1):
            user, created = User.objects.get_or_create(
                username=f'{DEMO_FAN_PREFIX}{i}',
                defaults={'first_name': 'Demo', 'last_name': f'Fan {i}', 'role': 'fan'},
            )
            if created:
                user.set_unusable_password()
                user.save()
                Fan.objects.create(user=user)
            fans.append(user)
        return fans

    def sell(self, event, seats, rows, cols, fans, demand, rng, totals):
        today = timezone.localdate()
        # Sales open up to 35 days before the match and stop on match day (or today).
        sales_end = min(event.event_date, today)
        sales_start = sales_end - timedelta(days=35)
        span = (sales_end - sales_start).days

        for seat in seats:
            # Popularity: front rows and seats near the halfway line sell more.
            front = 1 - (seat.row_number - 1) / max(rows - 1, 1)
            centre = 1 - abs((seat.seat_number - 1) / max(cols - 1, 1) - 0.5) * 2
            chance = demand * (0.25 + 0.6 * front + 0.7 * centre)
            if rng.random() > min(chance, 0.97):
                continue

            # Sales cluster towards match day.
            sold_on = sales_start + timedelta(days=int(span * (rng.random() ** 0.6)))
            sold_at = timezone.make_aware(datetime.combine(sold_on, time(rng.randint(7, 22), rng.randint(0, 59))))
            fan = rng.choice(fans)

            booking = Booking.objects.create(fan=fan, event=event, seat=seat, status='confirmed',
                                             hold_expires_at=sold_at + timedelta(minutes=10))
            Booking.objects.filter(pk=booking.pk).update(booking_date=sold_at)  # auto_now_add override

            late = rng.random() < 0.004  # the odd payment that arrived after the hold lapsed
            payment = Payment.objects.create(
                booking=booking, amount=seat.category.price, phone='254700000000',
                checkout_request_id=f'demo_{event.id}_{seat.id}',
                mpesa_reference=f'DEMO{rng.randint(10**6, 10**7 - 1)}',
                status='refund_due' if late else 'completed',
                result_code='0', result_desc='Demo payment', payment_date=sold_at + timedelta(minutes=1),
            )
            Payment.objects.filter(pk=payment.pk).update(created_at=sold_at)
            if late:
                Booking.objects.filter(pk=booking.pk).update(status='expired')
                totals['refunds'] += 1
                continue

            played = event.event_date < today
            used = played and rng.random() < 0.88  # most ticket holders turned up
            Ticket.objects.create(
                booking=booking, qr_token=Ticket.generate_qr_token(), is_used=used,
                used_at=timezone.make_aware(datetime.combine(event.event_date, event.event_time))
                - timedelta(minutes=rng.randint(5, 90)) if used else None,
            )
            totals['bookings'] += 1
            totals['revenue'] += float(seat.category.price)

    def clear(self):
        with transaction.atomic():
            events = Event.objects.filter(description__startswith=DEMO_MARKER)
            n_events = events.count()
            events.delete()  # cascades to bookings, payments, tickets, gate entries
            n_fans, _ = User.objects.filter(username__startswith=DEMO_FAN_PREFIX).delete()
        self.stdout.write(self.style.SUCCESS(f'Removed {n_events} demo matches and demo fans ({n_fans} rows).'))
